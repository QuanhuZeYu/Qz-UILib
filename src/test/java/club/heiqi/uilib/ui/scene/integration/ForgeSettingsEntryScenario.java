package club.heiqi.uilib.ui.scene.integration;

import java.io.InputStream;
import java.util.Collections;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import club.heiqi.uilib.testing.TestApplication;
import cpw.mods.fml.common.MetadataCollection;
import cpw.mods.fml.common.ModMetadata;

/** Forge真实解析成品元数据；防止源目录迁移后丢失信息而使GuiModList隐藏配置入口。 */
public final class ForgeSettingsEntryScenario extends TestApplication {
    public static void main(String[] args) throws Exception { new ForgeSettingsEntryScenario().run(args); }

    @Override protected void runTests() throws Exception {
        scenario("缺失元数据进入Forge隐藏配置按钮分支", () -> {
            ModMetadata missing=MetadataCollection.from(null,"missing-metadata")
                    .getMetadataForId("qz_uilib",Collections.emptyMap());
            require(missing.autogenerated,"缺失mcmod.info必须命中实际Forge自动元数据分支");
        });
        for(String artifact:arguments()) scenario("正式成品Forge元数据允许配置入口："+artifact, () -> {
            try(JarFile jar=new JarFile(artifact)) {
                JarEntry entry=jar.getJarEntry("mcmod.info");
                require(entry!=null,"MC成品缺少mcmod.info，Forge会隐藏已注册的配置按钮");
                ModMetadata metadata;
                try(InputStream input=jar.getInputStream(entry)) {
                    metadata=MetadataCollection.from(input,artifact)
                            .getMetadataForId("qz_uilib",Collections.emptyMap());
                }
                require(!metadata.autogenerated,"元数据modid未匹配，Forge仍隐藏配置按钮");
                require("Qz UILib".equals(metadata.name),"Forge显示名未正确展开");
                require(metadata.version!=null&&!metadata.version.isEmpty()&&!metadata.version.contains("$"),"Forge成品版本模板未展开");
                require(jar.getJarEntry("club/heiqi/uilib/host/client/settings/UILibGuiFactory.class")!=null,
                        "正式MC包缺配置工厂");
            }
        });
    }
}
