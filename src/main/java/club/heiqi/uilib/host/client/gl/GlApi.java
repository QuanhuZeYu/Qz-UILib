package club.heiqi.uilib.host.client.gl;

import java.nio.ByteBuffer;

/** 宿主GPU端口；算法不链接具体bindings或平台类。实例绑定单context/thread。 */
public interface GlApi {
    GlCapabilities capabilities();
    GlProgramAttribute glGetActiveAttribute(int program,int index);
    void glGetVertexAttribfv(int location,int pname,float[] values);
    void glDisableVertexAttribArray(int location);
    void glActiveTexture(int a);
    void glAttachShader(int a,int b);
    void glBindAttribLocation(int a,int b,String c);
    void glBindBuffer(int a,int b);
    void glBindFragDataLocation(int a,int b,String c);
    void glBindFramebuffer(int a,int b);
    void glBindSampler(int a,int b);
    void glBindTexture(int a,int b);
    void glBindVertexArray(int a);
    void glBlendColor(float a,float b,float c,float d);
    void glBlendEquationSeparate(int a,int b);
    void glBlendFuncSeparate(int a,int b,int c,int d);
    void glBufferData(int a,long b,int c);
    void glBufferData(int a,int[] b,int c);
    void glBufferSubData(int a,long b,ByteBuffer c);
    void glColorMask(boolean a,boolean b,boolean c,boolean d);
    void glCompileShader(int a);
    int glCreateProgram();
    int glCreateShader(int a);
    void glCullFace(int a);
    void glDeleteBuffers(int a);
    void glDeleteProgram(int a);
    void glDeleteShader(int a);
    void glDeleteTextures(int a);
    void glDeleteVertexArrays(int a);
    void glDepthFunc(int a);
    void glDepthMask(boolean a);
    void glDepthRange(double a,double b);
    void glDisable(int a);
    void glDrawElements(int a,int b,int c,long d);
    void glEnable(int a);
    void glEnableVertexAttribArray(int a);
    void glFrontFace(int a);
    int glGenBuffers();
    int glGenTextures();
    int glGenVertexArrays();
    boolean glGetBoolean(int a);
    void glGetBooleanv(int a,ByteBuffer b);
    float glGetFloat(int a);
    void glGetFloatv(int a,float[] b);
    int glGetInteger(int a);
    void glGetIntegerv(int a,int[] b);
    String glGetProgramInfoLog(int a);
    int glGetProgrami(int a,int b);
    String glGetShaderInfoLog(int a);
    int glGetShaderi(int a,int b);
    int glGetUniformLocation(int a,String b);
    boolean glIsEnabled(int a);
    void glLinkProgram(int a);
    void glPixelStorei(int a,int b);
    void glPolygonOffset(float a,float b);
    void glScissor(int a,int b,int c,int d);
    void glShaderSource(int a,String b);
    void glStencilFuncSeparate(int a,int b,int c,int d);
    void glStencilMaskSeparate(int a,int b);
    void glStencilOpSeparate(int a,int b,int c,int d);
    void glTexImage2D(int a,int b,int c,int d,int e,int f,int g,int h,ByteBuffer i);
    void glTexImage3D(int a,int b,int c,int d,int e,int f,int g,int h,int i,ByteBuffer j);
    void glTexParameteri(int a,int b,int c);
    void glTexSubImage2D(int a,int b,int c,int d,int e,int f,int g,int h,ByteBuffer i);
    void glTexSubImage3D(int a,int b,int c,int d,int e,int f,int g,int h,int i,int j,ByteBuffer k);
    void glUniform1f(int a,float b);
    void glUniform1i(int a,int b);
    void glUniform2f(int a,float b,float c);
    void glUniform3f(int a,float b,float c,float d);
    void glUniform3fv(int a,float[] b);
    void glUniformMatrix4fv(int a,boolean b,float[] c);
    void glUseProgram(int a);
    void glVertexAttribPointer(int a,int b,int c,boolean d,int e,long f);
    void glViewport(int a,int b,int c,int d);
}
