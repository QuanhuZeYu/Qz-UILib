package club.heiqi.uilib.ui.style;

/**
 * CSS border-style 枚举。
 *
 * <p>控制边框的线条样式。</p>
 */
public enum UiBorderStyle {

    /** 无边框。 */
    NONE,

    /** 实线边框。 */
    SOLID,

    /** 虚线边框。 */
    DASHED,

    /** 点线边框。 */
    DOTTED,

    /** 双线边框。 */
    DOUBLE,

    /** 隐藏边框（与 NONE 类似，但在表格边框合并时有区别）。 */
    HIDDEN
}
